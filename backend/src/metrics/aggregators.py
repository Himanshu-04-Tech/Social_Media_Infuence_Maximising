"""Aggregation and comparison utilities for algorithm metrics.

Constructs unified pandas DataFrames from metrics records, supporting
cross-algorithm sorting, ranking, and top-performer identification.
"""

from __future__ import annotations

from typing import Any, Sequence

import pandas as pd

from .models import MetricsRecord

# Canonical columns required by the SRS for algorithm comparison
METRICS_COLUMNS: list[str] = [
    "algorithm_name",
    "seed_count",
    "probability",
    "mean_influence",
    "min_influence",
    "max_influence",
    "std_influence",
    "influence_pct",
    "runtime_sec",
    "average_reach",
    "spread_efficiency",
    "node_count",
    "timestamp",
]


def aggregate_metrics(
    metrics_records: Sequence[MetricsRecord],
) -> pd.DataFrame:
    """Aggregate a sequence of MetricsRecord objects into a single pandas DataFrame.

    Produces a standardized comparison table conforming to the SRS specifications.

    Args:
        metrics_records: Sequence of MetricsRecord instances.

    Returns:
        pd.DataFrame containing all records indexed sequentially with standard columns.
    """
    if not metrics_records:
        return pd.DataFrame(columns=METRICS_COLUMNS)

    rows = [record.to_dict() for record in metrics_records]
    df = pd.DataFrame(rows)

    # Ensure all required columns exist and maintain standardized ordering
    for col in METRICS_COLUMNS:
        if col not in df.columns:
            df[col] = None

    return df[METRICS_COLUMNS]


def dataframe_from_metrics(
    metrics_records: Sequence[MetricsRecord],
) -> pd.DataFrame:
    """Utility alias to construct a pandas DataFrame from a list of MetricsRecord.

    Args:
        metrics_records: Sequence of MetricsRecord instances.

    Returns:
        pd.DataFrame formatted for cross-algorithm comparison.
    """
    return aggregate_metrics(metrics_records)


def sort_by_metric(
    df: pd.DataFrame,
    metric: str = "mean_influence",
    ascending: bool = False,
) -> pd.DataFrame:
    """Sort a metrics DataFrame by a specific performance indicator.

    Used for dashboard ranking and algorithm leaderboards.

    Args:
        df: Pandas DataFrame generated by aggregate_metrics.
        metric: Column name to sort by (default: 'mean_influence').
        ascending: True for ascending order, False for descending (default: False).

    Returns:
        A new pd.DataFrame sorted by the specified metric with reset index.

    Raises:
        ValueError: If the specified metric column is not present in the DataFrame.
    """
    if metric not in df.columns:
        raise ValueError(
            f"Metric '{metric}' not found in DataFrame columns: {list(df.columns)}"
        )

    return df.sort_values(by=metric, ascending=ascending).reset_index(drop=True)


def get_best_algorithm(
    source: pd.DataFrame | Sequence[MetricsRecord],
    metric: str = "mean_influence",
) -> dict[str, Any]:
    """Identify the top-performing algorithm based on a chosen metric.

    Args:
        source: Either an aggregated pd.DataFrame or a sequence of MetricsRecord.
        metric: Performance metric to maximize (default: 'mean_influence').

    Returns:
        Dictionary with keys:
            - 'algorithm': Name of the top algorithm
            - 'metric': Name of the evaluated metric
            - 'value': Maximum score achieved for that metric

    Raises:
        ValueError: If the source dataset is empty or if the metric does not exist.
    """
    df = aggregate_metrics(source) if isinstance(source, (list, tuple)) else source

    if df.empty:
        raise ValueError("Cannot determine best algorithm from an empty dataset.")

    if metric not in df.columns:
        raise ValueError(
            f"Metric '{metric}' not found in DataFrame columns: {list(df.columns)}"
        )

    best_idx = df[metric].idxmax()
    best_row = df.loc[best_idx]

    return {
        "algorithm": str(best_row["algorithm_name"]),
        "metric": metric,
        "value": float(best_row[metric]),
    }
